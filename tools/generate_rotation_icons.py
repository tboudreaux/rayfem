#!/usr/bin/env python3
"""Embed rotation SVGs, or copy a checked-in fallback after checking its inputs.

Run without arguments to refresh the checked-in header using rsvg-convert.
Meson writes a separate build-directory header with --output, so source trees
remain read-only during ordinary builds. No SVG renderer is needed when the
fallback matches the artwork and this generator.
"""

import argparse
import hashlib
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
ICONS = ("large_clockwise", "small_clockwise",
         "small_counter-clockwise", "large_counter-clockwise")
FALLBACK = ROOT / "src" / "app" / "rotation_icons_data.hpp"
DIGEST_PREFIX = "// Rotation artwork inputs SHA256: "
PIXELS = 120


def input_digest(assets):
    digest = hashlib.sha256()
    # Include generator logic as well as input bytes: a changed raster size or
    # embedding format must not silently reuse artwork made by an older script.
    # Normalize text line endings so Git's Windows checkout conversion does
    # not invalidate an otherwise identical portable fallback.
    digest.update(Path(__file__).read_text(encoding="utf-8").encode("utf-8"))
    for name in ICONS:
        data = (assets / (name + ".svg")).read_text(encoding="utf-8").encode("utf-8")
        digest.update(name.encode("utf-8") + b"\0")
        digest.update(len(data).to_bytes(8, "big"))
        digest.update(data)
    return digest.hexdigest()


def verified_fallback(path, digest):
    content = path.read_text(encoding="utf-8")
    recorded = re.search(r"^" + re.escape(DIGEST_PREFIX) + r"([0-9a-f]{64})$",
                         content, re.MULTILINE)
    if not recorded or recorded.group(1) != digest:
        raise ValueError(
            "Rotation icon fallback is stale: assets/rotation/*.svg or the "
            "generator changed. Install rsvg-convert (librsvg), then run "
            "python3 tools/generate_rotation_icons.py and include the updated "
            "src/app/rotation_icons_data.hpp. Reconfigure the build to use an "
            "installed converter automatically.")
    return content


def render(assets, converter, digest):
    output = ["// Generated by tools/generate_rotation_icons.py; do not edit.",
              DIGEST_PREFIX + digest,
              "#pragma once", "#include <array>", "#include <span>",
              "namespace RayFEM::UI::RotationArtwork {"]
    for i, name in enumerate(ICONS):
        # Preserve the complete viewBox. Both sizes share registration; the
        # small artwork intentionally occupies only the inner circular arc.
        source = assets / (name + ".svg")
        result = subprocess.run(
            [converter, "--width", str(PIXELS), "--height", str(PIXELS), str(source)],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)
        if result.returncode:
            raise ValueError(f"Could not render {source.name}: " +
                             result.stderr.decode("utf-8", errors="replace").strip())
        png = result.stdout
        if not png.startswith(b"\x89PNG\r\n\x1a\n"):
            raise ValueError(f"rsvg-convert did not produce a PNG for {source.name}")
        output.append(f"inline constexpr unsigned char icon{i}[] = {{")
        for offset in range(0, len(png), 16):
            output.append("    " + ",".join(f"0x{b:02x}" for b in png[offset:offset+16]) + ",")
        output.append("};")
    output.append("inline constexpr std::array<std::span<const unsigned char>,4> pngs{icon0,icon1,icon2,icon3};")
    output.append("} // namespace RayFEM::UI::RotationArtwork")
    return "\n".join(output) + "\n"


def write_if_changed(path, content):
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                         dir=path.parent, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(content)
        temporary.replace(path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=FALLBACK)
    parser.add_argument("--assets-dir", type=Path, default=ROOT / "assets" / "rotation")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--converter", help="Path to rsvg-convert; otherwise search PATH")
    mode.add_argument("--fallback", type=Path, help="Copy a verified header instead of rasterizing")
    mode.add_argument("--verify-fallback", type=Path, help="Only check that a fallback matches its inputs")
    args = parser.parse_args()
    try:
        digest = input_digest(args.assets_dir)
        if args.verify_fallback:
            verified_fallback(args.verify_fallback, digest)
            return 0
        if args.fallback:
            content = verified_fallback(args.fallback, digest)
        else:
            converter = args.converter or shutil.which("rsvg-convert")
            if not converter:
                raise ValueError("rsvg-convert is unavailable. Install librsvg to regenerate "
                                 "the icons, or use --fallback with a current checked-in header.")
            content = render(args.assets_dir, converter, digest)
        write_if_changed(args.output, content)
        return 0
    except (OSError, ValueError) as error:
        print(f"Rotation icons: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
